"""Writes import.compact.sql: the same import as import.sql, set-based (one JSON payload). Generated from courses.json."""
import json
from pathlib import Path
from build import PRICES, PLATFORM_INSTRUCTOR, NON_ADILO_LESSONS
from content import CATEGORIES
d = json.loads(Path('courses.json').read_text())
courses, sections, lessons = [], [], []
for c in d['courses']:
    pr = PRICES.get(c['adiloProject'])
    courses.append({k: c[k] for k in ['id', 'slug', 'title', 'subtitle', 'description', 'category', 'categorySlug', 'level', 'language', 'learningOutcomes', 'prerequisites', 'targetAudience', 'seoTitle', 'seoDescription', 'thumbnail']} | {
        'existing': c['existing'], 'price': None if c['existing'] else pr[0], 'originalPrice': None if c['existing'] else pr[1],
        'hours': round(c['durationSeconds'] / 3600, 1), 'videos': c['videoCount']})
    for s in c['sections']:
        sections.append({'id': s['id'], 'course': c['id'], 'title': s['title'], 'ord': s['order'], 'description': s['description']})
        for l in s['lessons']:
            lessons.append({'id': l['id'], 'section': s['id'], 'course': c['id'], 'title': l['title'], 'mins': l['durationMinutes'], 'free': l['freePreview'], 'ord': l['order'],
                            'vid': l['adiloFileId'], 'pid': l['adiloProjectId'], 'vtitle': l['originalTitle'], 'secs': l['durationSeconds']})
payload = json.dumps({'courses': courses, 'sections': sections, 'lessons': lessons, 'categories': CATEGORIES}, ensure_ascii=False, separators=(',', ':'))
assert '$edufy$' not in payload
sql = f"""-- Edufy Adilo import (compact form of import.sql, same result). Generated by compact.py.
begin;
create schema if not exists backup_20261122;
create table if not exists backup_20261122.courses as table public.courses;
create table if not exists backup_20261122.course_sections as table public.course_sections;
create table if not exists backup_20261122.lessons as table public.lessons;
create table if not exists backup_20261122.categories as table public.categories;
alter table public.course_sections add column if not exists description text;
alter table public.courses add column if not exists seo_title text;
alter table public.courses add column if not exists seo_description text;
create temp table _p on commit drop as select $edufy${payload}$edufy$::jsonb as j;
insert into public.categories (name, slug, description, is_active, position)
  select x->>'name', x->>'slug', x->>'description', true, 10 + (o - 1)::int from _p, jsonb_array_elements(j->'categories') with ordinality t(x, o)
  where not exists (select 1 from public.categories k where k.slug = x->>'slug');
-- existing courses: content only (prices, publish state, thumbnail, instructor unchanged; admin status marker kept)
update public.courses c set slug = x->>'slug', title = x->>'title', subtitle = x->>'subtitle', description = x->>'description', category = x->>'category',
  category_slug = x->>'categorySlug', level = x->>'level', language = x->>'language', seo_title = x->>'seoTitle', seo_description = x->>'seoDescription',
  learning_outcomes = x->'learningOutcomes', target_audience = x->'targetAudience',
  prerequisites = coalesce((select jsonb_agg(p) from jsonb_array_elements(c.prerequisites) p where p #>> '{{}}' like '\\_\\_status:%'), '[]'::jsonb) || (x->'prerequisites'),
  updated_at = now()
  from _p, jsonb_array_elements(j->'courses') x where (x->>'existing')::boolean and c.id = x->>'id';
-- new courses: drafts
insert into public.courses (id, slug, title, subtitle, description, category, category_slug, level, language, seo_title, seo_description, price, original_price,
  thumbnail_url, learning_outcomes, prerequisites, target_audience, instructor_id, is_published, duration_hours, total_lessons)
  select x->>'id', x->>'slug', x->>'title', x->>'subtitle', x->>'description', x->>'category', x->>'categorySlug', x->>'level', x->>'language', x->>'seoTitle', x->>'seoDescription',
    (x->>'price')::numeric, (x->>'originalPrice')::numeric, x->>'thumbnail', x->'learningOutcomes', '["__status:draft"]'::jsonb || (x->'prerequisites'), x->'targetAudience',
    '{PLATFORM_INSTRUCTOR}'::uuid, false, (x->>'hours')::numeric, (x->>'videos')::int
  from _p, jsonb_array_elements(j->'courses') x where not (x->>'existing')::boolean
  on conflict (id) do update set slug = excluded.slug, title = excluded.title, subtitle = excluded.subtitle, description = excluded.description, category = excluded.category,
    category_slug = excluded.category_slug, level = excluded.level, language = excluded.language, seo_title = excluded.seo_title, seo_description = excluded.seo_description,
    learning_outcomes = excluded.learning_outcomes, target_audience = excluded.target_audience, updated_at = now();
insert into public.course_sections (id, course_id, title, section_order, description)
  select x->>'id', x->>'course', x->>'title', (x->>'ord')::int + 100, x->>'description' from _p, jsonb_array_elements(j->'sections') x
  on conflict (id) do update set title = excluded.title, section_order = excluded.section_order, description = excluded.description;
insert into public.lessons (id, section_id, course_id, title, duration_minutes, type, is_free_preview, lesson_order, adilo_file_id, adilo_project_id, adilo_embed_url, video_title, video_duration, video_status)
  select x->>'id', x->>'section', x->>'course', x->>'title', (x->>'mins')::int, 'video', (x->>'free')::boolean, (x->>'ord')::int, x->>'vid', x->>'pid', 'https://adilo.bigcommand.com/watch/' || (x->>'vid'), x->>'vtitle', (x->>'secs')::int, 'library'
  from _p, jsonb_array_elements(j->'lessons') x
  on conflict (id) do update set section_id = excluded.section_id, course_id = excluded.course_id, title = excluded.title, duration_minutes = excluded.duration_minutes,
    is_free_preview = excluded.is_free_preview, lesson_order = excluded.lesson_order, adilo_file_id = excluded.adilo_file_id, adilo_project_id = excluded.adilo_project_id,
    adilo_embed_url = excluded.adilo_embed_url, video_title = excluded.video_title, video_duration = excluded.video_duration;
update public.course_sections s set section_order = (x->>'ord')::int from _p, jsonb_array_elements(j->'sections') x where s.id = x->>'id';
update public.course_sections set section_order = 99 where id in ({', '.join("'" + n['section'] + "'" for n in NON_ADILO_LESSONS)});
update public.courses c set total_lessons = (select count(*) from public.lessons l where l.course_id = c.id),
  duration_hours = round(coalesce((select sum(coalesce(l.video_duration, l.duration_minutes * 60)) from public.lessons l where l.course_id = c.id), 0) / 3600.0, 1)
  where c.id in (select x->>'id' from _p, jsonb_array_elements(j->'courses') x);
commit;
"""
Path('import.compact.sql').write_text(sql)
print(len(sql), 'bytes')
